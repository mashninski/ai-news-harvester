def fix_user(card_text: str, flagged: list[dict]) -> str:
    """flagged: [{n, sentence, hits: [(found, avoid, prefer, note)]}]"""
    parts = [f"Тэкст карткі:\n<card>\n{card_text}\n</card>\n\nПазначаныя сказы:"]
    for f in flagged:
        why = "; ".join(f"«{found}» — слоўнік: «{avoid}» → {' / '.join(prefer)}" + (f" ({note})" if note else "")
                        for found, avoid, prefer, note in f["hits"])
        parts.append(f"\n{f['n']}. {f['sentence']}\n   Лінтар: {why}")
    return "\n".join(parts)
