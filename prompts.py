def _glossary_block(entries: list[dict]) -> str:
    lines = []
    for e in entries:
        parts = [f"{slug(e['term'])} | {e['term']} → {e['be']}"]
        if e.get("alt"):
            parts.append("дапушчальна: " + ", ".join(e["alt"]))
        if e.get("avoid"):
            parts.append("не: " + ", ".join(e["avoid"]))
        if e.get("note"):
            parts.append(e["note"])
        lines.append(" | ".join(parts))
    return "\n".join(lines)


def _calques_block(entries: list[dict]) -> str:
    lines = []
    for e in entries:
        line = f"«{e['avoid']}» → {' / '.join(e.get('prefer', []))}"
        if e.get("note"):
            line += f" — {e['note']}"
        if e.get("example_bad"):
            line += f" (дрэнна: {e['example_bad']} добра: {e.get('example_good', '')})"
        lines.append(line)
    return "\n".join(lines)


def _names_block(entries: list[dict]) -> str:
    """Имя пишется так, как его пишет модель (write, наркамаўка); форма на сайте —
    только где конвертер её меняет: её видит судья корпуса, и без неё он счёл бы
    «Ўілісан» на сайте расхождением с «Уілісан» из списка."""
    lines = []
    for e in entries:
        line = f"{e['en']} → {e['write']}"
        if e.get("be") and e["be"] != e["write"]:
            line += f" (на сайце: {e['be']})"
        if e.get("who"):
            line += f" — {e['who']}"
        lines.append(line)
    return "\n".join(lines)


@lru_cache(maxsize=4)
def reference_block(site: Path) -> str:
    """Стайлгайд, глоссарий и антикальки целиком — один неизменный текст.
    Любой изменившийся байт здесь сбрасывает кэш, поэтому ничего переменного
    (дат, счётчиков) сюда не попадает."""
    c = site / "claude"
    style = (c / "ai-news-styleguide.md").read_text(encoding="utf-8")
    glossary = json.loads((c / "ai-news-glossary.json").read_text(encoding="utf-8"))["entries"]
    calques = json.loads((c / "ai-news-anti-calques.json").read_text(encoding="utf-8"))["entries"]
    names = json.loads((c / "ai-news-names.json").read_text(encoding="utf-8"))["entries"]
    return (
        "ДАВЕДКА: стайлгайд, глосарый і антыкалькавы слоўнік беларускай стужкі навін пра ШІ.\n\n"
        "<styleguide>\n" + style.strip() + "\n</styleguide>\n\n"
        "<glossary>\nФармат радка: слаг | англійскі тэрмін → як пісаць | дапушчальныя варыянты | "
        "чаго пазбягаць | нататка. Напісанне ў глосарыі — у тарашкевіцы; ты пішаш тое ж слова "
        "наркамаўкай (навучаньне → навучанне), тарашкевіцу зробіць канвертар.\n"
        + _glossary_block(glossary) + "\n</glossary>\n\n"
        "<anti_calques>\nРусізмы і калькі — не ўжываць, бяры замену справа:\n"
        + _calques_block(calques) + "\n</anti_calques>\n\n"
        "<names>\nНапісанне імёнаў людзей: як у крыніцы → як пішаш ты (наркамаўка). Імя са спісу "
        "пішы менавіта так і скланяй як звычайнае слова («Саймона Уілісана»). Імя, якога няма ў "
        "спісе, транслітаруй па гучанні (стайлгайд, §2.2) і пішы адным напісаннем на ўсю картку.\n"
        + _names_block(names) + "\n</names>"
    )


def cached_system(site: Path, task: str) -> list[dict]:
    return [
        {"type": "text", "text": reference_block(site), "cache_control": {"type": "ephemeral", "ttl": "1h"}},
        {"type": "text", "text": task},
    ]


